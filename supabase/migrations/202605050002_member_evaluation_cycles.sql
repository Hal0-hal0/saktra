create table if not exists public.member_evaluation_cycle (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  started_at timestamp with time zone not null default now(),
  title text not null default 'Member Evaluation',
  evaluation_open boolean not null default true,
  evaluation_deadline date
);

alter table public.member_evaluation_response
  add column if not exists cycle_id bigint references public.member_evaluation_cycle(id) on delete cascade;

create index if not exists member_evaluation_cycle_open_idx
  on public.member_evaluation_cycle(evaluation_open);

create index if not exists member_evaluation_response_cycle_idx
  on public.member_evaluation_response(cycle_id);

create unique index if not exists member_evaluation_response_once_per_cycle_idx
  on public.member_evaluation_response(cycle_id, evaluator_id, target_user_id)
  where cycle_id is not null;
